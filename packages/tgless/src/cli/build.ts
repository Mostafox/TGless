import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import { MARKER, type ManifestPayload } from './manifest-protocol.js';
import type { ResolvedConfig } from './config.js';
import { CliError, color, formatBytes, log } from './log.js';
import { platformPlugin, sdkStubPlugin } from './plugins.js';

const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SHIMS = path.join(PKG_ROOT, 'shims');

const GENERATED = '// AUTO-GENERATED by tgless — do not edit. Source: src/ (run `tgless build`).';

/** Names imported from `sdk/db` by schema.js; a table export must not shadow them. */
const DSL_NAMES = new Set(['table', 'integer', 'text', 'real', 'numeric', 'blob', 'boolean', 'json', 'index', 'uniqueIndex', 'check', 'primaryKey', 'sql']);

export interface Manifest {
  updates: string[];
  endpoints: string[];
  commands: { command: string; description: string }[];
  tables: { tableName: string; exportName: string }[];
  /** Generated tgcloud/schema.js source. */
  schema: string;
}

export interface BuildResult {
  manifest: Pick<Manifest, 'updates' | 'endpoints' | 'commands'> & { tables: string[] };
  files: { file: string; size: number }[];
  durationMs: number;
}

const toPosix = (p: string) => p.split(path.sep).join('/');

function formatEsbuildErrors(e: unknown): never {
  const errors = (e as esbuild.BuildFailure)?.errors;
  if (errors?.length) {
    const text = esbuild.formatMessagesSync(errors, { kind: 'error', color: !!process.stdout.isTTY }).join('\n');
    throw new CliError(`Build failed:\n${text}`);
  }
  throw e;
}

/**
 * Pass 1: bundle the app for Node with a stubbed `sdk`, then read `app.manifest()`
 * in a fresh process: which update types, endpoints and entities the app uses.
 */
export async function collectManifest(cfg: ResolvedConfig): Promise<Manifest> {
  if (!fs.existsSync(cfg.entryPath)) {
    throw new CliError(`Entry not found: ${path.relative(cfg.root, cfg.entryPath)} (set \`entry\` in tgless.config.ts).`);
  }
  fs.mkdirSync(cfg.cacheDir, { recursive: true });
  const out = path.join(cfg.cacheDir, 'manifest.mjs');
  try {
    await esbuild.build({
      stdin: {
        contents: `import app from ${JSON.stringify(toPosix(cfg.entryPath))};
export default app;
`,
        resolveDir: cfg.root,
        sourcefile: 'tgless-manifest.js',
        loader: 'js',
      },
      outfile: out,
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node18',
      packages: 'external',
      alias: cfg.alias,
      define: cfg.define,
      plugins: [sdkStubPlugin()],
      logLevel: 'silent',
    });
  } catch (e) {
    formatEsbuildErrors(e);
  }

  const runner = path.join(PKG_ROOT, 'dist', 'cli', 'manifest-runner.js');
  const stdout = await new Promise<string>((resolve, reject) => {
    execFile(process.execPath, [runner, out], { cwd: cfg.root, maxBuffer: 64 * 1024 * 1024 }, (err, so, se) => {
      if (err && !so.includes(MARKER)) reject(new CliError(`Could not load your app:\n${se || err.message}`));
      else resolve(so);
    });
  });
  const line = stdout.split('\n').find((l) => l.startsWith(MARKER));
  const payload = JSON.parse(line!.slice(MARKER.length)) as ManifestPayload;
  if (!payload.ok) {
    if (payload.error === 'NOT_APP') throw new CliError(`${cfg.entry} must \`export default createApp({...})\`.`);
    if (payload.error === 'LOAD') {
      throw new CliError(`Your app threw while loading (top-level code runs at build time to discover routes):
${payload.message}`);
    }
    throw new CliError(payload.message ?? 'Failed to read the app manifest.');
  }
  return payload as Required<ManifestPayload> as unknown as Manifest;
}

function checkTableExports(manifest: Manifest) {
  for (const e of manifest.tables) {
    if (DSL_NAMES.has(e.exportName)) {
      throw new CliError(
        `Entity "${e.tableName}" would be exported from schema.js as "${e.exportName}", which shadows an sdk/db function. ` +
          `Set \`exportName\` in its entity() options (e.g. { exportName: '${e.exportName}Table' }).`,
      );
    }
  }
}

function clean(outDir: string) {
  for (const sub of ['handlers', 'endpoints', 'lib']) fs.rmSync(path.join(outDir, sub), { recursive: true, force: true });
  fs.rmSync(path.join(outDir, 'schema.js'), { force: true });
}

function write(file: string, contents: string) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

function entrySource(cfg: ResolvedConfig) {
  const lines = [
    "import * as sdk from 'sdk';",
    "import * as dbModule from 'sdk/db';",
    "import * as schema from '../schema.js';",
    `import app from ${JSON.stringify(toPosix(cfg.entryPath))};`,
  ];
  if (cfg.fetchShim) {
    lines.push(
      "if (typeof globalThis.fetch !== 'function') {",
      '  globalThis.fetch = (input, init) => sdk.fetch(typeof input === "string" ? input : String(input && input.url ? input.url : input), init);',
      '}',
    );
  }
  lines.push('app.bind({ sdk, dbModule, schema });', 'export { app };', '');
  return lines.join('\n');
}

/** Shims for Node globals; injected only when the bundle actually references the global. */
const GLOBAL_SHIMS = [
  { name: 'Buffer', file: 'buffer.js', used: /(?<![.\w$])Buffer\s*[.(]/ },
  { name: 'process', file: 'process.js', used: /(?<![.\w$])process\s*[.[]/ },
];

function bundleOptions(cfg: ResolvedConfig, problems: PlatformProblem[], inject: string[]): esbuild.BuildOptions {
  return {
    stdin: { contents: entrySource(cfg), resolveDir: cfg.root, sourcefile: 'tgless-entry.js', loader: 'js' },
    outfile: path.join(cfg.outDir, 'lib', 'app.js'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: cfg.target,
    mainFields: ['browser', 'module', 'main'],
    conditions: ['worker', 'browser', 'import', 'default'],
    minify: cfg.minify,
    keepNames: true,
    treeShaking: true,
    legalComments: 'eof',
    charset: 'utf8',
    define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis', ...cfg.define },
    inject,
    alias: cfg.alias,
    plugins: [platformPlugin({ polyfills: cfg.polyfills, allowEmpty: cfg.stubBuiltins, problems })],
    banner: { js: `${GENERATED}\n// lib/app.js = your app + its npm dependencies, bundled.` },
    metafile: true,
    logLevel: 'silent',
  };
}

type PlatformProblem = { pkg: string; builtin: string; importer: string };

/** Pass 2: bundle the app + npm dependencies into `tgcloud/lib/app.js`. */
async function bundleApp(cfg: ResolvedConfig): Promise<esbuild.Metafile> {
  let problems: PlatformProblem[] = [];
  let result: esbuild.BuildResult<{ metafile: true }>;
  try {
    let inject: string[] = [];
    if (cfg.polyfills) {
      // Probe build: which Node globals does the code use?
      const probe = await esbuild.build({ ...bundleOptions(cfg, problems, []), write: false, minify: false });
      const code = probe.outputFiles!.map((f) => f.text).join('\n');
      inject = GLOBAL_SHIMS.filter((s) => s.used.test(code)).map((s) => path.join(SHIMS, s.file));
      problems = [];
    }
    result = (await esbuild.build(bundleOptions(cfg, problems, inject))) as esbuild.BuildResult<{ metafile: true }>;
  } catch (e) {
    formatEsbuildErrors(e);
  }
  if (problems.length) {
    const byPkg = new Map<string, Set<string>>();
    for (const p of problems) {
      if (!byPkg.has(p.pkg)) byPkg.set(p.pkg, new Set());
      byPkg.get(p.pkg)!.add(p.builtin);
    }
    const lines = [...byPkg].map(([pkg, b]) => `  • ${color.bold(pkg)} imports ${[...b].map((x) => `"${x}"`).join(', ')}`);
    const all = [...new Set(problems.map((p) => p.builtin))];
    fs.rmSync(path.join(cfg.outDir, 'lib'), { recursive: true, force: true });
    throw new CliError(
      [
        'Some dependencies need Node.js built-ins, which tgcloud does not have:',
        ...lines,
        '',
        'Options:',
        `  - use a browser/edge-compatible library instead (look for "browser", "edge" or "worker" support);`,
        `  - install an npm polyfill and map it: alias: { ${all.map((b) => `'${b}': '<polyfill-package>'`).join(', ')} };`,
        `  - if the code path is never used, stub it: stubBuiltins: [${all.map((b) => `'${b}'`).join(', ')}]`,
        '(both in tgless.config.ts)',
      ].join('\n'),
    );
  }
  return result!.metafile;
}

function validateBundle(cfg: ResolvedConfig, metafile: esbuild.Metafile) {
  const allowed = (p: string) => p === 'sdk' || p.startsWith('sdk/') || p === '../schema.js';
  for (const [file, out] of Object.entries(metafile.outputs)) {
    for (const imp of out.imports) {
      if (!imp.external) continue;
      if (!allowed(imp.path)) {
        throw new CliError(`${file} imports "${imp.path}", which does not exist on tgcloud. Only sdk modules and bundled code are allowed.`);
      }
      if (imp.kind === 'require-call') {
        throw new CliError(`${file} uses require("${imp.path}"). tgcloud modules are ESM; use import instead.`);
      }
    }
  }
}

/** Build the project into `tgcloud/`. */
export async function buildProject(cfg: ResolvedConfig, opts: { quiet?: boolean } = {}): Promise<BuildResult> {
  const started = Date.now();
  const manifest = await collectManifest(cfg);
  checkTableExports(manifest);

  clean(cfg.outDir);
  write(path.join(cfg.outDir, 'schema.js'), manifest.schema);
  const metafile = await bundleApp(cfg);
  validateBundle(cfg, metafile);

  for (const type of manifest.updates) {
    write(
      path.join(cfg.outDir, 'handlers', `${type}.js`),
      `${GENERATED}\nimport { app } from '../lib/app.js';\n\nexport default function (payload, ctx) {\n  return app.handle('${type}', payload, ctx);\n}\n`,
    );
  }
  for (const name of manifest.endpoints) {
    write(
      path.join(cfg.outDir, 'endpoints', `${name}.js`),
      `${GENERATED}\nimport { app } from '../lib/app.js';\n\nexport default function (input, ctx) {\n  return app.callEndpoint('${name}', input, ctx);\n}\n`,
    );
  }

  const files = listFiles(cfg.outDir).map((f) => ({ file: toPosix(path.relative(cfg.root, f)), size: fs.statSync(f).size }));
  for (const f of files) {
    if (f.size > cfg.maxFileSize) log.warn(`${f.file} is ${formatBytes(f.size)} (over ${formatBytes(cfg.maxFileSize)}). Consider lighter dependencies.`);
  }
  const summary = {
    updates: manifest.updates,
    endpoints: manifest.endpoints,
    commands: manifest.commands,
    tables: manifest.tables.map((t) => t.tableName),
  };
  write(path.join(cfg.cacheDir, 'manifest.json'), JSON.stringify(summary, null, 2));

  const result = { manifest: summary, files, durationMs: Date.now() - started };
  if (!opts.quiet) printSummary(result);
  return result;
}

function listFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(p));
    else if (entry.name.endsWith('.js')) out.push(p);
  }
  return out.sort();
}

export function printSummary(r: BuildResult) {
  const width = Math.max(...r.files.map((f) => f.file.length));
  for (const f of r.files) log.info(`  ${f.file.padEnd(width)}  ${color.dim(formatBytes(f.size))}`);
  const m = r.manifest;
  log.ok(
    `Built in ${r.durationMs}ms — ${m.updates.length} handler(s), ${m.endpoints.length} endpoint(s), ${m.tables.length} table(s).`,
  );
  if (!m.updates.length && !m.endpoints.length) log.warn('The app has no routes or endpoints yet.');
}
